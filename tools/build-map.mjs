// Builds assets/map-dots.js: the world map as a dot grid (like the journal's dot-grid pages).
// Run once:  npm i d3-geo topojson-client world-atlas@2  &&  node tools/build-map.mjs
// Projection is plain equirectangular, so script.js can place people with simple lat/lon math.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { geoContains } from "d3-geo";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve("world-atlas/land-50m.json"), "utf8"));
const land = feature(topo, topo.objects.land);

const W = 1000, LAT_TOP = 84, LAT_BOTTOM = -58;
const H = ((LAT_TOP - LAT_BOTTOM) / 360) * W;
const STEP = 6;
const toLon = (x) => (x / W) * 360 - 180;
const toLat = (y) => LAT_TOP - (y / W) * 360;

let d = "", count = 0;
for (let y = STEP / 2; y < H; y += STEP) {
  let lastX = null;
  for (let x = STEP / 2; x < W; x += STEP) {
    if (!geoContains(land, [toLon(x), toLat(y)])) continue;
    const r = (n) => +n.toFixed(1);
    d += lastX === null ? `M${r(x)} ${r(y)}h0` : `m${r(x - lastX)} 0h0`;
    lastX = x; count++;
  }
}
const out = process.argv[2] || "assets/map-dots.js";
writeFileSync(out, `// Generated by tools/build-map.mjs. ${count} dots.\nwindow.WW_MAP = ${JSON.stringify({ w: W, h: +H.toFixed(2), latTop: LAT_TOP, step: STEP, d })};\n`);
console.log(count, "dots,", d.length, "chars");
